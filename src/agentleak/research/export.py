"""Paper-ready exports of a benchmark run.

``agentleak bench export RUN`` writes, into ``RUN/exports/``:

``tables.tex``      booktabs tables; each caption states the metric definition,
                    denominator, interval method, software version and tier,
                    with a provenance note under the table
``tables.md``       the same tables in Markdown
``metrics.csv``     every metric record, one per line, with version, tier and
                    provenance columns (for plotting)
``scenarios.csv``   one line per scenario (repetitions pooled)
``methods.txt``     a plain-text Methods paragraph describing exactly what ran
``references.bib``  BibTeX for AgentLeak and the data sources used
"""

from __future__ import annotations

import csv
import io
from pathlib import Path
from typing import Any

from .bench import BenchRun, load_run
from .citation import references_bib
from .render import (
    agentrisk_rows,
    channel_rows,
    detection_rows,
    fmt_ci,
    fmt_estimate,
    fmt_frac,
    provenance_line,
    tier_line,
)
from .rows import scenario_table

FORMATS = ("latex", "markdown", "csv", "methods", "bibtex")

_LATEX_SPECIAL = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}",
}


def latex_escape(text: str) -> str:
    return "".join(_LATEX_SPECIAL.get(ch, ch) for ch in str(text))


_INTERVAL_NAMES = {"wilson": "Wilson score", "clopper-pearson": "Clopper-Pearson exact"}


def interval_name(summary: dict[str, Any]) -> str:
    method = str(summary.get("settings", {}).get("interval", "wilson"))
    return _INTERVAL_NAMES.get(method, method)


def _conf(summary: dict[str, Any]) -> int:
    return round(float(summary.get("settings", {}).get("confidence", 0.95)) * 100)


def _counts_phrase(summary: dict[str, Any]) -> str:
    c = summary.get("counts", {})
    parts = [f"{c.get('leaking', 0)} leaking fixtures"]
    if c.get("clean_independent"):
        parts.append(f"{c['clean_independent']} independent clean controls")
    if c.get("clean_derived"):
        parts.append(f"{c['clean_derived']} derived clean counterparts")
    if c.get("live"):
        parts.append(f"{c['live']} live-run scenarios")
    return ", ".join(parts)


def _latex_table(
    rows: list[tuple[str, dict[str, Any]]], caption: str, label: str, note: str
) -> str:
    lines = [
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        r"\begin{tabular}{lrrl}",
        r"\toprule",
        r"Metric & Estimate & $k/n$ & CI \\",
        r"\midrule",
    ]
    for name, rec in rows:
        lines.append(
            f"{latex_escape(name)} & {fmt_estimate(rec)} & {latex_escape(fmt_frac(rec))} & "
            f"{fmt_ci(rec, sep='--')} \\\\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        "",
        f"\\par\\smallskip\\footnotesize {note}",
        r"\end{table}",
    ]
    return "\n".join(lines)


def _note(summary: dict[str, Any]) -> str:
    settings = summary.get("settings", {})
    return latex_escape(
        f"AgentLeak {summary.get('software', {}).get('agentleak_version', '?')}; detection "
        f"{tier_line(summary)} Data: {provenance_line(summary)}. Seed "
        f"{settings.get('seed')}; manifest SHA-256 {str(settings.get('manifest_sha256', ''))[:16]}."
    )


def latex_tables(summary: dict[str, Any]) -> str:
    """All booktabs tables of a run (``\\usepackage{booktabs}`` required)."""
    conf = _conf(summary)
    interval = interval_name(summary)
    version = summary.get("software", {}).get("agentleak_version", "?")
    mode = summary.get("detector", {}).get("mode", "?")
    note = _note(summary)
    out = [
        "% Generated by agentleak bench export. Requires \\usepackage{booktabs}.",
        "",
    ]
    det = detection_rows(summary)
    if det:
        caption = latex_escape(
            f"Detection performance of AgentLeak {version} ({mode} tier) on "
            f"{_counts_phrase(summary)}. Recall: leaking fixtures with at least one detector "
            "finding on a disclosure channel over leaking fixtures. Specificity: clean units "
            "with no finding over clean units, reported separately for independent clean "
            "controls and derived counterparts, never pooled. Labels are fixed by "
            "construction; the detectors received no ground truth. "
            f"{conf}% {interval} intervals."
        )
        out += [_latex_table(det, caption, "tab:agentleak-detection", note), ""]
    ch = channel_rows(summary)
    if ch:
        caption = latex_escape(
            "Where detected leaks travel: share of leaking units with a detector finding on "
            "each disclosure channel (a unit can leak on several). Internal-only: detected "
            "leaks with no finding on the final output, over detected leaks, i.e. leaks an "
            f"output-only audit would miss. {conf}% {interval} intervals."
        )
        out += [_latex_table(ch, caption, "tab:agentleak-channels", note), ""]
    ar = agentrisk_rows(summary)
    if ar:
        caption = latex_escape(
            "AgentRisk Risk Index (RI = WSL / rho_S, level weights 1-4, observed-vault "
            "denominator per unit). Means and pooled RI with "
            f"{conf}% BCa bootstrap intervals "
            f"({summary.get('settings', {}).get('bootstrap_resamples')} resamples)."
        )
        out += [_latex_table(ar, caption, "tab:agentleak-agentrisk", note), ""]
    return "\n".join(out)


def markdown_tables(summary: dict[str, Any]) -> str:
    conf = _conf(summary)
    lines = [f"<!-- Generated by agentleak bench export. {conf}% intervals. -->", ""]
    for title, rows in (("Detection performance", detection_rows(summary)),
                        ("Where detected leaks travel", channel_rows(summary)),
                        ("AgentRisk", agentrisk_rows(summary))):
        if not rows:
            continue
        lines += [f"### {title}", "", "| Metric | Estimate | k/n | CI | Method |",
                  "|---|---:|---:|---|---|"]
        for name, rec in rows:
            lines.append(f"| {name} | {fmt_estimate(rec)} | {fmt_frac(rec)} | {fmt_ci(rec)} | "
                         f"{rec.get('ci_method', '')} |")
        lines.append("")
    lines += [
        f"AgentLeak {summary.get('software', {}).get('agentleak_version', '?')}; detection "
        f"{tier_line(summary)} Data: {provenance_line(summary)}.",
        "",
    ]
    return "\n".join(lines)


_METRIC_COLUMNS = (
    "experiment", "id", "kind", "definition", "population", "group", "group_value",
    "numerator", "denominator", "n", "estimate", "ci_low", "ci_high", "ci_method",
    "confidence", "agentleak_version", "detector_mode", "tiers_run", "degraded",
    "provenance", "manifest_sha256",
)


def metrics_csv(summary: dict[str, Any]) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=list(_METRIC_COLUMNS), lineterminator="\n")
    writer.writeheader()
    det = summary.get("detector", {})
    shared = {
        "experiment": summary.get("experiment", ""),
        "agentleak_version": summary.get("software", {}).get("agentleak_version", ""),
        "detector_mode": det.get("mode", ""),
        "tiers_run": ";".join(det.get("tiers_run", [])),
        "degraded": int(bool(det.get("degraded"))),
        "provenance": provenance_line(summary),
        "manifest_sha256": summary.get("settings", {}).get("manifest_sha256", ""),
    }
    for rec in summary.get("metrics", []):
        writer.writerow({**shared, **{k: rec.get(k, "") for k in _METRIC_COLUMNS
                                      if k not in shared}})
    return buf.getvalue()


def scenarios_csv(rows: list[dict[str, Any]]) -> str:
    cols = ["scenario_id", "source", "origin_id", "domain", "failure_mode", "adversary",
            "label", "negative_kind", "counterpart_of", "repetitions", "leaked",
            "leak_fraction", "ri", "wsl", "rho_s", "channels", "reference_channels",
            "data_types", "degraded"]
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(cols)
    for rec in scenario_table(rows):
        out = []
        for c in cols:
            v = rec[c]
            if isinstance(v, set):
                v = ";".join(sorted(v))
            elif isinstance(v, float):
                v = repr(round(v, 6))
            out.append(v)
        writer.writerow(out)
    return buf.getvalue()


def methods_paragraph(run: BenchRun) -> str:
    """A plain-text Methods paragraph describing exactly what this run did."""
    s, lock, m = run.summary, run.lock, run.manifest
    env = lock.get("environment", {})
    det = s.get("detector", {})
    counts = s.get("counts", {})
    commit = (env.get("git") or {}).get("commit")
    per_source: dict[str, int] = {}
    for rec in scenario_table(run.rows):
        if rec["label"] in ("leaking", "live"):
            per_source[rec["source"]] = per_source.get(rec["source"], 0) + 1
    licences = {p["source"]: p.get("license", "") for p in s.get("provenance", [])}
    items = [f"{src} ({n}, {licences.get(src) or 'licence not stated'})"
             for src, n in per_source.items()]
    sources = items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]
    detectors = det.get("detectors", "all")
    if isinstance(detectors, dict):
        off = sorted(k for k, v in detectors.items() if not v)
        det_phrase = "all built-in detectors except " + ", ".join(off) if off else \
            "all built-in detectors"
    else:
        det_phrase = "all built-in detectors"
    conf = _conf(s)
    settings = s.get("settings", {})
    text = [
        f"We ran AgentLeak {s.get('software', {}).get('agentleak_version')}"
        + (f" (commit {commit[:12]})" if commit else "")
        + f" with the {det.get('mode')} detection tier (tiers run: "
        f"{', '.join(det.get('tiers_run', []))}; {det_phrase}"
        + ("; obscured-copy matching on" if det.get("obscured_copies") else "")
        + ").",
    ]
    if m.agent.mode == "live":
        text.append(
            f"Each scenario context was given to {m.agent.model} through an OpenAI-compatible "
            f"endpoint ({m.repetitions} repetition(s) per scenario, temperature "
            f"{m.agent.temperature}, at most {m.agent.max_steps} steps), and every captured "
            "trace was analyzed."
        )
    else:
        text.append(
            "Fixed traces were replayed and analyzed once each; no model was called."
        )
    text.append(
        f"The corpus comprised {counts.get('leaking', 0) or counts.get('live', 0)} leaking "
        f"fixtures from {len(items)} source(s), {sources}"
        + (f", {counts['clean_independent']} independent clean controls"
           if counts.get("clean_independent") else "")
        + (f" and {counts['clean_derived']} derived clean counterparts, each obtained by "
           "removing from a pack fixture every disclosure-channel event that contains one of "
           "its ground-truth values" if counts.get("clean_derived") else "")
        + "."
    )
    text.append(
        "Labels were fixed by construction and the detectors received no ground truth. A "
        "unit counted as a detected leak when at least one finding fell on a disclosure "
        "channel (tool call, shared memory, inter-agent message, log, generated file or "
        "final output); user input and tool responses are sources of data, not disclosures."
    )
    text.append(
        "The AgentRisk Risk Index was computed as RI = WSL / rho_S with level weights "
        "1, 2, 3, 4 and the observed reachable set of each trace as the vault."
    )
    text.append(
        f"Proportions are reported with {conf}% {interval_name(s)} intervals; "
        f"means, the pooled Risk Index and F1 with {conf}% BCa bootstrap intervals "
        f"({settings.get('bootstrap_resamples')} resamples, seed {settings.get('seed')}). "
        "Independent and derived negatives are reported separately and never pooled."
    )
    outputs = lock.get("outputs", {})
    text.append(
        f"The run is reproducible from its manifest (SHA-256 "
        f"{str(settings.get('manifest_sha256', ''))[:16]}) with `agentleak bench run`; the "
        f"row-level output has SHA-256 {str(outputs.get('rows.csv', ''))[:16]}."
    )
    return " ".join(text) + "\n"


def latex_p(p: float) -> str:
    return "$<$0.0001" if p < 1e-4 else f"{p:.4f}"


def comparison_latex(doc: dict[str, Any]) -> str:
    """A booktabs table of a paired comparison."""
    conf = round(doc["settings"]["confidence"] * 100)
    caption = latex_escape(
        f"Paired comparison of {doc['b']['experiment']} (B) with {doc['a']['experiment']} (A) "
        f"over {doc['paired_units']} scenarios. Differences are B - A with {conf}% paired "
        f"bootstrap intervals ({doc['settings']['bootstrap_resamples']} resamples); p-values "
        "from exact McNemar tests (rates) or sign-flip tests (mean RI), Holm-adjusted over "
        "all rows."
    )
    note = latex_escape(
        f"A: agentleak {doc['a']['agentleak_version']}, {doc['a']['detector'].get('mode')} "
        f"[{', '.join(doc['a']['detector'].get('tiers_run', []))}]. B: agentleak "
        f"{doc['b']['agentleak_version']}, {doc['b']['detector'].get('mode')} "
        f"[{', '.join(doc['b']['detector'].get('tiers_run', []))}]. Comparability warnings: "
        + ("; ".join(c["detail"] for c in doc["checks"] if c["status"] != "ok") or "none")
        + "."
    )
    lines = [
        "% Generated by agentleak bench compare. Requires \\usepackage{booktabs}.",
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        f"\\caption{{{caption}}}",
        r"\label{tab:agentleak-comparison}",
        r"\begin{tabular}{lrrrlrr}",
        r"\toprule",
        r"Metric & A & B & $\Delta$ & CI & $p$ & $p_{\mathrm{Holm}}$ \\",
        r"\midrule",
    ]
    for r in doc["metrics"]:
        d = r["difference"]

        def side(x: dict[str, Any]) -> str:
            if "numerator" in x:
                return f"{x['estimate']:.3f} ({x['numerator']}/{x['denominator']})"
            return f"{x['estimate']:.3f}"

        lines.append(
            f"{latex_escape(r['label'])} & {side(r['a'])} & {side(r['b'])} & "
            f"{d['estimate']:+.3f} & {d['ci_low']:+.3f} to {d['ci_high']:+.3f} & "
            f"{latex_p(r['test']['p_value'])} & {latex_p(r['p_holm'])} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", "",
              f"\\par\\smallskip\\footnotesize {note}", r"\end{table}", ""]
    return "\n".join(lines)


def export_run(
    run: BenchRun | str | Path,
    formats: tuple[str, ...] | list[str] = FORMATS,
    out_dir: str | Path | None = None,
) -> dict[str, Path]:
    """Write the requested exports and return ``{name: path}``."""
    r = run if isinstance(run, BenchRun) else load_run(run)
    unknown = [f for f in formats if f not in FORMATS]
    if unknown:
        raise ValueError(f"unknown export format(s) {unknown}; choose from {', '.join(FORMATS)}")
    out = Path(out_dir) if out_dir else r.out_dir / "exports"
    out.mkdir(parents=True, exist_ok=True)
    written: dict[str, Path] = {}

    def write(name: str, text: str) -> None:
        path = out / name
        path.write_text(text, encoding="utf-8")
        written[name] = path

    if "latex" in formats:
        write("tables.tex", latex_tables(r.summary))
    if "markdown" in formats:
        write("tables.md", markdown_tables(r.summary))
    if "csv" in formats:
        write("metrics.csv", metrics_csv(r.summary))
        write("scenarios.csv", scenarios_csv(r.rows))
    if "methods" in formats:
        write("methods.txt", methods_paragraph(r))
    if "bibtex" in formats:
        write("references.bib", references_bib(r.lock.get("sources", [])))
    return written


