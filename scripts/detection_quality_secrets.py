"""Credential coverage: which token formats the deterministic tier recognises.

The PII pages measure recall on labelled personal data. Credentials need their
own count, because the question is different: not "is this value sensitive"
but "does the detector know this provider's format at all".

Method
------
``scripts/secret_samples.py`` generates three synthetic tokens per format (54
formats: provider keys, JWTs, private keys, connection strings), seeded and
assembled at run time so no token-shaped string is committed. Each token is
placed in three carriers — a sentence, a bare log line and a JSON value under
a neutral key — and counts as found when any carrier yields the expected data
type with a matched value that contains the token or is contained in it.
A token found only as some other type is a type confusion, counted as a miss.

Precision is measured on ``scripts/detection_hard_negatives.json``: the share
of hard-negative texts on which a *credential* type fires, through the full
fast pipeline.

This is a coverage measurement on formats chosen and generated by the same
author as the rules; it shows which formats are known, not how rules behave on
real-world keys, which a public repository cannot hold.

    python scripts/detection_quality_secrets.py
    python scripts/detection_quality_secrets.py --installed   # measure the importable version
    python scripts/detection_quality_secrets.py --json out.json --markdown out.md
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

SCRIPTS = Path(__file__).resolve().parent
if "--installed" not in sys.argv:
    sys.path.insert(0, str(SCRIPTS.parent / "src"))
sys.path.insert(1, str(SCRIPTS))

from secret_samples import BUILDERS, samples  # noqa: E402

import agentleak  # noqa: E402
from agentleak.core.runner import analyze  # noqa: E402
from agentleak.core.trace import Trace  # noqa: E402
from agentleak.detectors import build_detectors  # noqa: E402

CARRIERS = (
    "Deploying the service with {token} now.",
    "{token}",
    '{{"setting": "{token}"}}',
)
CREDENTIAL_TYPES = {
    "api_key", "aws_access_key", "github_token", "slack_token", "stripe_key", "llm_api_key",
    "google_api_key", "jwt", "bearer_token", "private_key", "connection_string",
    "secret_assignment",
}
HARD_NEGATIVES = SCRIPTS / "detection_hard_negatives.json"


def _wilson(hits: int, total: int, z: float = 1.96) -> tuple[float, float]:
    if total == 0:
        return (0.0, 0.0)
    p = hits / total
    denom = 1 + z * z / total
    centre = (p + z * z / (2 * total)) / denom
    margin = z * ((p * (1 - p) / total + z * z / (4 * total * total)) ** 0.5) / denom
    return (max(0.0, centre - margin), min(1.0, centre + margin))


def evaluate() -> dict[str, Any]:
    detectors = build_detectors(None, None)
    per_rule: dict[str, dict[str, int]] = defaultdict(lambda: {"hit": 0, "confused": 0, "missed": 0})
    for rule, expected, token in samples(per_rule=3):
        found_expected = False
        found_any: set[str] = set()
        for carrier in CARRIERS:
            text = carrier.format(token=token)
            for d in detectors:
                for m in d.detect(text):
                    if m.matched_value in token or token in m.matched_value:
                        found_any.add(m.data_type)
                        if m.data_type == expected:
                            found_expected = True
        key = "hit" if found_expected else ("confused" if found_any else "missed")
        per_rule[rule][key] += 1

    rows = []
    for rule in BUILDERS:
        c = per_rule[rule]
        n = c["hit"] + c["confused"] + c["missed"]
        rows.append({"format": rule, "expected": BUILDERS[rule][0], **c, "n": n,
                     "recall": round(c["hit"] / n, 4) if n else 0.0})
    hits = sum(r["hit"] for r in rows)
    total = sum(r["n"] for r in rows)
    formats_found = sum(1 for r in rows if r["hit"] == r["n"])

    data = json.loads(HARD_NEGATIVES.read_text(encoding="utf-8"))
    texts = [t for group in data["categories"].values() for t in group]
    flagged: list[dict[str, str]] = []
    for text in texts:
        trace = Trace.model_validate({"run_id": "hn", "agent_name": "a", "events": [
            {"event_id": "e1", "channel": "log", "source": "a", "target": "b", "content": text}]})
        hits_here = [f for f in analyze(trace).findings if f.data_type in CREDENTIAL_TYPES]
        if hits_here:
            flagged.append({"text": text, "types": sorted({f.data_type for f in hits_here})})

    low, high = _wilson(hits, total)
    flow, fhigh = _wilson(len(flagged), len(texts))
    return {
        "software_version": agentleak.__version__,
        "detector_tier": "fast (deterministic: regex + dictionaries)",
        "source": "synthetic tokens from scripts/secret_samples.py (seed 20261114, 3 per format)",
        "recall": round(hits / total, 4) if total else 0.0,
        "ci95": [round(low, 4), round(high, 4)],
        "numerator": hits,
        "denominator": total,
        "formats": len(rows),
        "formats_fully_found": formats_found,
        "by_format": rows,
        "hard_negatives": {
            "texts": len(texts),
            "flagged_with_a_credential_type": len(flagged),
            "rate": round(len(flagged) / len(texts), 4) if texts else 0.0,
            "ci95": [round(flow, 4), round(fhigh, 4)],
            "detail": flagged,
        },
        "note": (
            "Coverage of known formats on generated tokens, written by the same author as the "
            "rules. It shows which formats are recognised, not behaviour on real-world keys."
        ),
    }


def to_markdown(report: dict[str, Any]) -> str:
    out = [
        f"AgentLeak {report['software_version']} · tier: {report['detector_tier']}",
        f"Ground truth: {report['source']}.",
        "",
        f"**Recall {report['recall']:.3f}** ({report['numerator']}/{report['denominator']}, "
        f"95% CI {report['ci95'][0]:.3f}–{report['ci95'][1]:.3f}); "
        f"{report['formats_fully_found']} of {report['formats']} formats fully found.",
        "",
        "| Format | Expected type | Found | Wrong type | Missed | n |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for r in report["by_format"]:
        out.append(f"| `{r['format']}` | `{r['expected']}` | {r['hit']} | {r['confused']} | "
                   f"{r['missed']} | {r['n']} |")
    hn = report["hard_negatives"]
    out += [
        "",
        f"Hard negatives: {hn['flagged_with_a_credential_type']} of {hn['texts']} texts flagged "
        f"with a credential type (rate {hn['rate']:.3f}, 95% CI {hn['ci95'][0]:.3f}–{hn['ci95'][1]:.3f}).",
    ]
    for item in hn["detail"][:20]:
        out.append(f"- {', '.join(item['types'])}: {item['text']}")
    out += ["", report["note"], "", "Reproduce with `python scripts/detection_quality_secrets.py`."]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--json")
    parser.add_argument("--markdown")
    parser.add_argument("--installed", action="store_true")
    args = parser.parse_args()
    report = evaluate()
    if args.json:
        Path(args.json).write_text(json.dumps(report, indent=2) + "\n")
    if args.markdown:
        Path(args.markdown).write_text(to_markdown(report))
    if not args.json and not args.markdown:
        print(to_markdown(report))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
